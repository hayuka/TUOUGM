<h2 id="press-overview-ja">01. PROJECT OVERVIEW</h2>
<h3>THE ULTIMATE SIN OF UNBUILT GUNPLA MOUNTAIN (TUOUGM)</h3>
<p><strong>Born from Hardcore. Built on Gunpla. Driven by Noise.</strong></p>
<p>TUOUGM（トゥーオGM）は、ガンプラ文化をテーマにした日本発の音楽プロジェクト。</p>
<p>1980年代のハードコアパンクをルーツに、パンク、メタル、オルタナティブロック、エレクトロニックなど、ジャンルの枠にとらわれない楽曲を制作している。</p>
<p>積みプラ、制作への情熱、コレクター心理など、ガンプラファンならではの体験を、ユーモアとエネルギーに満ちた音楽として表現する。</p>
</section>

<section class="press-kit__section" aria-labelledby="press-bio-ja">
<h2 id="press-bio-ja">02. ARTIST BIOGRAPHY</h2>
<div class="press-kit__copy-grid">
<div>
<h3>Biography</h3>
<p>TUOUGMは、1980年代の日本のハードコアパンクシーンで活動したミュージシャンによって立ち上げられた音楽プロジェクト。</p>
<p>その音楽的背景には、ハードコアパンクをはじめ、スラッシュメタル、ニューウェーブ、オルタナティブロックなど、さまざまなジャンルからの影響がある。</p>
<p>かつてのバンド活動で培った音楽的感覚と、長年親しんできたガンプラ文化を組み合わせ、現在はAIを含むデジタル制作技術を活用して楽曲と映像を制作している。</p>
<p>音楽ジャンルを固定せず、ガンプラを作る人、積む人、集める人の喜びや葛藤を、時にシリアスに、時にユーモラスに描いている。</p>
<h3>BACKGROUND / SELECTED HISTORY</h3>
<ul>
<li><strong>1980年代</strong> — 14歳でハードコアパンクバンド「LOST FIGHTS」を結成。ベーシストとして活動を開始。</li>
<li><strong>1989年</strong> — フランスのPanx Productionsによる7インチ盤『Panx Vinyl Zine 03』に、LOST FIGHTSの「We Shall Over Come」が収録される。</li>
<li><strong>その後</strong> — OIL SHOCK、Manekin、NEARMISSなど、ジャンルの異なるバンドで活動。</li>
<li><strong>現在</strong> — ハードコアパンクを出発点とする音楽的背景とガンプラ文化を融合させ、TUOUGMとして楽曲・映像制作を展開。</li>
</ul>
</div>
</div>
</section>

