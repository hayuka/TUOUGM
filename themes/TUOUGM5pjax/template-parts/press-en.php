<h2 id="press-overview-en">01. PROJECT OVERVIEW</h2>
<h3>THE ULTIMATE SIN OF UNBUILT GUNPLA MOUNTAIN (TUOUGM)</h3>
<p><strong>Born from Hardcore. Built on Gunpla. Driven by Noise.</strong></p>
<p>TUOUGM (pronounced "Too-Oh-G-M") is a music project from Japan built around Gunpla culture.</p>
<p>Rooted in the Japanese hardcore punk scene of the 1980s, TUOUGM creates genre-bending music that draws from punk, metal, alternative rock, electronic music, and beyond.</p>
<p>From the thrill of building model kits to the obsession with collecting and stacking unopened boxes, TUOUGM turns the experiences of Gunpla enthusiasts into music filled with energy, humor, and attitude.</p>
</section>

<section class="press-kit__section" aria-labelledby="press-bio-en">
<h2 id="press-bio-en">02. ARTIST BIOGRAPHY</h2>
<div class="press-kit__copy-grid">
<div>
<h3>Biography</h3>
<p>TUOUGM was founded by a musician with roots in Japan's 1980s hardcore punk scene.</p>
<p>Its musical influences extend beyond hardcore punk to thrash metal, new wave, alternative rock, and other genres.</p>
<p>Combining the musical instincts developed through years of band experience with a lifelong passion for Gunpla, the project now uses modern digital production techniques, including AI-assisted tools, to create original music and videos.</p>
<p>Rather than committing to a single genre, TUOUGM explores the joys, frustrations, and obsessions of Gunpla builders and collectors — sometimes seriously, often with a sense of humor.</p>
<h3>BACKGROUND / SELECTED HISTORY</h3>
<ul>
<li><strong>1980s</strong> — Formed the hardcore punk band LOST FIGHTS at age 14 and began performing as a bassist.</li>
<li><strong>1989</strong> — LOST FIGHTS' track "We Shall Over Come" appeared on <em>Panx Vinyl Zine 03</em>, a 7-inch release by France's Panx Productions.</li>
<li><strong>Later years</strong> — Played in bands including OIL SHOCK, Manekin, and NEARMISS, exploring different musical styles.</li>
<li><strong>Today</strong> — Brings together a hardcore punk background and Gunpla culture through TUOUGM's music and visual productions.</li>
</ul>
</div>
